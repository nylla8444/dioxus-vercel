//! `init-ci`: writes a GitHub Actions workflow that builds the app and
//! deploys it with dioxus-vercel, plus the GitHub Actions side of `deploy`.

use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

/// Where `init-ci` writes the workflow.
pub fn workflow_path(repo: &Path) -> PathBuf {
    repo.join(".github")
        .join("workflows")
        .join("dioxus-vercel.yml")
}

/// Turns off Vercel's own Git deployments, which can't build Dioxus apps
/// and would run next to the workflow's deploys.
pub const VERCEL_JSON: &str = "{\n  \"git\": { \"deploymentEnabled\": false }\n}\n";

/// The `__NAME__` placeholders are filled in by [`workflow`]. They avoid
/// braces, which GitHub Actions uses for its own `${{ }}` expressions.
const WORKFLOW_TEMPLATE: &str = r#"# Generated by dioxus-vercel init-ci.
# Pushes to main deploy to production. Pull requests deploy a preview and
# get a comment with its link.
name: Deploy to Vercel

on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read
  pull-requests: write

concurrency:
  group: vercel-${{ github.ref }}
  cancel-in-progress: true

jobs:
  deploy:
    # Pull requests from forks don't get repository secrets, so skip them.
    if: github.event_name == 'push' || github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: __WORKDIR__
    env:
      VERCEL_TOKEN: ${{ secrets.VERCEL_TOKEN }}
    steps:
      - uses: actions/checkout@v7

      - uses: dtolnay/rust-toolchain@stable
        with:
          targets: wasm32-unknown-unknown

      # Keeps Rust's build output between runs.
      - uses: Swatinem/rust-cache@v2
        with:
          workspaces: __WORKDIR__

      - uses: cargo-bins/cargo-binstall@v1.24.0

      # dx must be the same version as the project's dioxus crate.
      - name: Install dx
        run: cargo binstall dioxus-cli@__DIOXUS_VERSION__ --no-confirm

      - name: Install the Vercel CLI
        run: npm install --global vercel@__VERCEL_VERSION__

      - name: Install dioxus-vercel
        run: __INSTALL_DIOXUS_VERCEL__

      - name: Deploy
        id: deploy
        run: dioxus-vercel deploy__DEPLOY_ARGS__ ${{ github.event_name == 'push' && '--prod' || '' }}

      - name: Comment with the preview link
        if: github.event_name == 'pull_request'
        uses: actions/github-script@v9
        env:
          URL: ${{ steps.deploy.outputs.url }}
        with:
          script: |
            const marker = '<!-- dioxus-vercel -->';
            const body = `${marker}\nPreview: ${process.env.URL}\n\nIt needs a Vercel login to view while Deployment Protection is on.`;
            const { owner, repo } = context.repo;
            const issue_number = context.issue.number;
            const comments = await github.paginate(github.rest.issues.listComments, { owner, repo, issue_number });
            const previous = comments.find((comment) => comment.body?.includes(marker));
            if (previous) {
              await github.rest.issues.updateComment({ owner, repo, comment_id: previous.id, body });
            } else {
              await github.rest.issues.createComment({ owner, repo, issue_number, body });
            }
"#;

pub struct WorkflowOptions<'a> {
    /// The Dioxus project's folder, relative to the repository root.
    pub workdir: &'a str,
    /// Package to deploy, for workspaces with more than one.
    pub package: Option<&'a str>,
    pub dioxus_version: &'a str,
    /// npm version spec for the Vercel CLI, such as `65` or `latest`.
    pub vercel_version: &'a str,
}

pub fn workflow(options: &WorkflowOptions) -> String {
    let install = format!(
        "cargo install dioxus-vercel --version {} --locked",
        env!("CARGO_PKG_VERSION")
    );
    let deploy_args = options
        .package
        .map(|package| format!(" --package {package}"))
        .unwrap_or_default();
    WORKFLOW_TEMPLATE
        .replace("__WORKDIR__", options.workdir)
        .replace("__DEPLOY_ARGS__", &deploy_args)
        .replace("__DIOXUS_VERSION__", options.dioxus_version)
        .replace("__VERCEL_VERSION__", options.vercel_version)
        .replace("__INSTALL_DIOXUS_VERCEL__", &install)
}

/// CI services, GitHub Actions included, set `CI` to a non-empty value.
pub fn running_in_ci() -> bool {
    std::env::var_os("CI").is_some_and(|value| !value.is_empty() && value != "false")
}

/// The closest folder at or above `start` that holds a `.git` folder (or a
/// `.git` file, as in worktrees and submodules).
pub fn repo_root(start: &Path) -> Option<PathBuf> {
    start
        .ancestors()
        .find(|dir| dir.join(".git").exists())
        .map(Path::to_path_buf)
}

/// `project` relative to `repo`, written with `/` the way workflows expect.
pub fn workdir(repo: &Path, project: &Path) -> Result<String> {
    let relative = project
        .strip_prefix(repo)
        .with_context(|| format!("{} is not inside {}", project.display(), repo.display()))?;
    let parts: Vec<String> = relative
        .components()
        .map(|part| part.as_os_str().to_string_lossy().into_owned())
        .collect();
    Ok(if parts.is_empty() {
        ".".to_owned()
    } else {
        parts.join("/")
    })
}

/// Writes `contents` to `path` unless it exists, in which case `force`
/// decides. Creates missing parent folders.
pub fn write_new(path: &Path, contents: &str, force: bool) -> Result<()> {
    if path.exists() && !force {
        bail!(
            "{} already exists. Pass --force to replace it.",
            path.display()
        );
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, contents).with_context(|| format!("could not write {}", path.display()))
}

/// Inside GitHub Actions, exposes the deployment URL as the step's `url`
/// output and adds it to the job summary.
pub fn report_to_github(url: &str) -> Result<()> {
    if let Some(path) = std::env::var_os("GITHUB_OUTPUT") {
        append(Path::new(&path), &format!("url={url}\n"))?;
    }
    if let Some(path) = std::env::var_os("GITHUB_STEP_SUMMARY") {
        append(Path::new(&path), &format!("Deployed to {url}\n"))?;
    }
    Ok(())
}

fn append(path: &Path, line: &str) -> Result<()> {
    let mut file = OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
        .with_context(|| format!("could not open {}", path.display()))?;
    file.write_all(line.as_bytes())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn generate() -> String {
        workflow(&WorkflowOptions {
            workdir: "examples/hello",
            package: None,
            dioxus_version: "0.7.10",
            vercel_version: "65",
        })
    }

    #[test]
    fn passes_the_package_to_deploy() {
        assert!(generate().contains("run: dioxus-vercel deploy ${{"));
        let yaml = workflow(&WorkflowOptions {
            workdir: ".",
            package: Some("web"),
            dioxus_version: "0.7.10",
            vercel_version: "latest",
        });
        assert!(yaml.contains("run: dioxus-vercel deploy --package web ${{"));
    }

    #[test]
    fn fills_in_every_placeholder() {
        let yaml = generate();
        assert!(!yaml.contains("__"), "placeholder left in:\n{yaml}");
        assert!(yaml.contains("working-directory: examples/hello"));
        assert!(yaml.contains("workspaces: examples/hello"));
        assert!(yaml.contains("cargo binstall dioxus-cli@0.7.10 --no-confirm"));
        assert!(yaml.contains("npm install --global vercel@65"));
        assert!(yaml.contains(&format!(
            "cargo install dioxus-vercel --version {} --locked",
            env!("CARGO_PKG_VERSION")
        )));
    }

    #[test]
    fn keeps_github_expressions_intact() {
        let yaml = generate();
        assert!(yaml.contains("VERCEL_TOKEN: ${{ secrets.VERCEL_TOKEN }}"));
        assert!(yaml.contains("${{ github.event_name == 'push' && '--prod' || '' }}"));
        assert!(yaml.contains("URL: ${{ steps.deploy.outputs.url }}"));
    }

    #[test]
    fn workdir_is_relative_with_forward_slashes() {
        let repo = Path::new("/repo");
        assert_eq!(workdir(repo, Path::new("/repo")).unwrap(), ".");
        assert_eq!(
            workdir(repo, Path::new("/repo/examples/hello")).unwrap(),
            "examples/hello"
        );
        assert!(workdir(repo, Path::new("/elsewhere")).is_err());
    }

    #[test]
    fn finds_the_repo_root_above_a_project() {
        let tmp = std::env::temp_dir().join(format!("dioxus-vercel-ci-{}", std::process::id()));
        let project = tmp.join("examples").join("hello");
        fs::create_dir_all(&project).unwrap();
        fs::create_dir_all(tmp.join(".git")).unwrap();

        assert_eq!(repo_root(&project), Some(tmp.clone()));
        fs::remove_dir_all(&tmp).unwrap();
    }

    #[test]
    fn write_new_refuses_to_overwrite_without_force() {
        let tmp = std::env::temp_dir().join(format!("dioxus-vercel-write-{}", std::process::id()));
        let file = tmp.join("a").join("b.yml");

        write_new(&file, "one", false).unwrap();
        assert!(write_new(&file, "two", false).is_err());
        assert_eq!(fs::read_to_string(&file).unwrap(), "one");
        write_new(&file, "two", true).unwrap();
        assert_eq!(fs::read_to_string(&file).unwrap(), "two");
        fs::remove_dir_all(&tmp).unwrap();
    }
}
